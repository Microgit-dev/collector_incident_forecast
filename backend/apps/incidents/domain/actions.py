def next_actions(incident_type: str, top_hypothesis: str | None, is_forecast: bool = False) -> list[Step]:
    if is_forecast:
        return FORECAST
    if incident_type in BY_THREAT:
        steps = list(BY_THREAT[incident_type])
        if top_hypothesis == "false":
            steps = FALSE_ALARM + steps
        elif top_hypothesis == "works":
            steps = BY_HYPOTHESIS["works"] + steps
        return steps
    return BY_HYPOTHESIS.get(top_hypothesis or "unknown", BY_HYPOTHESIS["unknown"])
